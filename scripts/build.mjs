/**
 * Build the shipped client artifact: Vite compiles the browser half to CommonJS,
 * then this script wraps it in the DSH module-loader factory so `require('react')`
 * resolves through the host page. The host half (`lib/index.js`) is plain ESM
 * JavaScript and is shipped as-is.
 */

import { execFileSync } from 'node:child_process'
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bin = (name) => resolve(root, 'node_modules', '.bin', name)
const ID = 'dsh-workspace-session-search'

execFileSync(bin('vite'), ['build', '--logLevel', 'warn'], { cwd: root, stdio: 'inherit' })

const cjsPath = resolve(root, 'dist', 'client.cjs')
const outPath = resolve(root, 'dist', 'client.js')
const cjs = readFileSync(cjsPath, 'utf8')
const wrapped = `/* ${ID} — generated by scripts/build.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: '${ID}',
  factory(require) {
    const module = { exports: {} }
    const exports = module.exports
    try {
${cjs
  .split('\n')
  .map((line) => '      ' + line)
  .join('\n')}
    } catch (error) {
      console.error('[${ID}] client bundle failed', error)
      throw error
    }
    return Object.prototype.hasOwnProperty.call(module.exports, 'default') ? module.exports.default : module.exports
  },
})
`
writeFileSync(outPath, wrapped)
rmSync(cjsPath)
process.stdout.write(`[build] wrapped dist/client.js (${wrapped.length} bytes)\n`)
